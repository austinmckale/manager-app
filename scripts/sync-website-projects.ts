// Rebuilds src/lib/website-project-catalog.ts from the website's own gallery, so Past jobs only
// offers projects the website still shows, with the photos the website chose.
//   node --import tsx scripts/sync-website-projects.ts "C:/Users/Alivia/Documents/ChatGPT/RHIPros"
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const site = process.argv[2];
if (!site) throw new Error("Pass the website repository folder.");
const load = (file: string) => import(pathToFileURL(resolve(site, file)).href);

type Image = { src: string; alt: string };
type Study = { slug: string; title: string; summary: string; locationName: string; serviceName: string; solution: string; scope: string[]; results: string[]; images: Image[]; beforeImages?: Image[] };

async function main() {
  const { galleryCaseStudies } = (await load("src/content/caseStudies.ts")) as { galleryCaseStudies: Study[] };
  const { curatePhotos } = (await load("src/content/photoCuration.ts")) as { curatePhotos: (images: readonly Image[], shown?: Iterable<string>) => Image[] };
  const catalog = galleryCaseStudies.map((study) => ({
    slug: study.slug,
    title: study.title,
    location: study.locationName,
    service: study.serviceName,
    description: study.summary,
    solution: study.solution,
    scope: study.scope,
    results: study.results,
    // The website's curation drops near-duplicates and clutter shots; keep its order, hero first.
    images: curatePhotos(study.images).slice(0, 8),
  })).filter((project) => project.images.length > 0);
  const out = `// Generated by scripts/sync-website-projects.ts from the website's project gallery. Do not edit by hand.
export type WebsiteCatalogProject = { slug: string; title: string; location: string; service: string; description: string; solution: string; scope: string[]; results: string[]; images: { src: string; alt: string }[] };

export const WEBSITE_ORIGIN = "https://www.rhipros.com";

export const websiteProjectCatalog: WebsiteCatalogProject[] = ${JSON.stringify(catalog, null, 2)};
`;
  writeFileSync(resolve("src/lib/website-project-catalog.ts"), out);
  console.log(`Wrote ${catalog.length} projects: ${catalog.map((project) => `${project.slug} (${project.images.length})`).join(", ")}`);
}

main();
